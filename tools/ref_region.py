#!/usr/bin/env python3
"""
Dump every chunk of a Java world as golden NBT for the region-reader tests.

`mcme` must produce the same bytes from an .mca file that the reference does.
Phase 2 did this for NBT documents in isolation (tools/ref_dump.py); this does
it for the chunk payloads that a real region file wraps around them, which is
what actually exercises the container: the sector table, the 5-byte chunk
header, and the zlib/gzip framing.

The decompressed payload is loaded with amulet_nbt and written back out, so the
golden .nbt files are the reference's own re-serialisation of the chunk. That
is deliberate — it normalises away nothing, but it does mean the golden bytes
are a canonical form the reference itself agrees with rather than whatever
happened to be in the file.

Usage:
    venv/bin/python tools/ref_region.py --world tests/golden/worlds/java \\
        --out tests/golden/world
"""

from __future__ import annotations

import argparse
import os
import struct
import sys
import zlib

import amulet_nbt


def _log(msg: str) -> None:
    print(f"ref_region: {msg}", file=sys.stderr)


def iter_region(path: str):
    """Yield (cx, cz, compression_byte, payload_bytes) for every present chunk.

    Reads the sector table directly rather than through a library, so the test
    pins the container layout rather than whatever amulet happens to expose.
    """
    with open(path, "rb") as fh:
        data = fh.read()

    if len(data) < 8192:
        raise ValueError(f"{path} is {len(data)} bytes, shorter than the header")

    # The slot index is local to the region: chunk (cx, cz) lives at
    # (cx & 31) + (cz & 31) * 32. Recover the true coordinates from the file
    # name so the caller sees world coordinates.
    base = os.path.basename(path)
    rx = int(base.split(".")[1])
    rz = int(base.split(".")[2])

    for slot in range(1024):
        loc_at = slot * 4
        sector_offset = int.from_bytes(data[loc_at:loc_at + 3], "big")
        if sector_offset == 0:
            continue

        at = sector_offset * 4096
        (length,) = struct.unpack(">I", data[at:at + 4])
        comp = data[at + 4]
        payload = data[at + 5:at + 5 + length - 1]

        lx = slot % 32
        lz = slot // 32
        yield rx * 32 + lx, rz * 32 + lz, comp, payload


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--world", default="tests/golden/worlds/java")
    ap.add_argument("--out", default="tests/golden/world")
    args = ap.parse_args()

    region_dir = os.path.join(args.world, "region")
    if not os.path.isdir(region_dir):
        _log(f"no region/ directory in {args.world}")
        return 1

    os.makedirs(args.out, exist_ok=True)

    names = sorted(n for n in os.listdir(region_dir) if n.endswith(".mca"))
    if not names:
        _log(f"no .mca files in {region_dir}")
        return 1

    index_lines = []
    for region_name in names:
        region_path = os.path.join(region_dir, region_name)
        stem = region_name[: -len(".mca")]

        for cx, cz, comp, payload in iter_region(region_path):
            if comp == 1:
                raw = zlib.decompress(payload, 15 + 16)   # gzip
                codec = "gzip"
            elif comp == 2:
                raw = zlib.decompress(payload, 15)         # zlib
                codec = "zlib"
            elif comp == 3:
                raw = payload
                codec = "store"
            else:
                _log(f"  {stem} chunk ({cx}, {cz}): compression byte {comp}, skipped")
                continue

            tag = amulet_nbt.load(raw, compressed=False, little_endian=False)

            base = f"{stem}.{cx}.{cz}"
            with open(os.path.join(args.out, base + ".nbt"), "wb") as fh:
                fh.write(tag.save_to(compressed=False, little_endian=False))
            with open(os.path.join(args.out, base + ".snbt"), "w",
                      encoding="utf-8") as fh:
                # Compact, matching the convention tools/ref_dump.py uses for
                # the NBT golden vectors: mcme's compact SNBT is the form the
                # reference emits with indent=None, and that is what the self
                # tests compare against.
                fh.write(tag.to_snbt())

            index_lines.append(f"{stem} {cx} {cz} {codec} {len(raw)}")
            _log(f"  {base}: {codec}, {len(raw)} bytes of NBT")

    with open(os.path.join(args.out, "MANIFEST.txt"), "w", encoding="utf-8") as fh:
        fh.write("# region cx cz codec raw-nbt-bytes  (generated by tools/ref_region.py)\n")
        for line in index_lines:
            fh.write(line + "\n")

    _log(f"wrote {len(index_lines)} chunks to {args.out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
