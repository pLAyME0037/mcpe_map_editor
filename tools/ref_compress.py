#!/usr/bin/env python3
"""
Generate golden compression vectors for the mcme compression layer.

Phase 3 needs gzip (Java/Bedrock `level.dat`, some Anvil chunk payloads), zlib
(other Anvil chunk payloads) and LZ4 (Bedrock subchunks from 1.18.2 on).

We cannot test a decompressor by round-tripping it through its own compressor:
that only proves the pair is self-consistent, and says nothing about whether
Minecraft can read what we produce. So this script uses Python's own `zlib` and
`lz4.block` — independent implementations, and the same codecs the games use —
to produce vectors that `src/compress/selftest.c` must inflate exactly.

Vectors are committed, not generated at test time, for the same reason as
tests/golden/nbt: `./rebuild.sh test` must not require a Python environment.

Usage:
    python3 tools/ref_compress.py --out tests/golden/compress
"""

from __future__ import annotations

import argparse
import os
import random
import sys
import zlib


def _log(msg: str) -> None:
    print(f"ref_compress: {msg}", file=sys.stderr)


def payloads() -> dict[str, bytes]:
    """The byte patterns worth testing, each named after the file it lands in.

    The interesting properties:
      text      ordinary compression, exercises the common path
      zeros     extreme run-length, the best-case ratio
      random    incompressible, so the compressor must not expand much and the
                decompressor must handle a stream that is nearly all literals
      nuls      binary data with embedded NULs, which catches any code that
                treats a payload as a C string
      tiny      1 byte, the smallest thing that is still a valid stream
      big       ~256 KiB, long enough to cross the 64 KiB streaming chunks in
                inflate_stream()/deflate_stream() several times over rather
                than fitting in one
    """
    rng = random.Random(0xC0FFEE)
    return {
        "text": (b"The quick brown fox jumps over the lazy dog. " * 64),
        "zeros": bytes(10_000),
        "random": bytes(rng.randrange(256) for _ in range(10_000)),
        "nuls": b"\x00\x01\x00\x02binary\x00with\x00nuls\x00" * 512,
        "tiny": b"x",
        "big": (bytes(rng.randrange(256) for _ in range(4096)) * 64),
    }


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--out", default="tests/golden/compress")
    args = ap.parse_args()

    os.makedirs(args.out, exist_ok=True)

    try:
        import lz4.block  # type: ignore
    except ImportError:
        lz4 = None
        _log("WARNING: python lz4 not installed; LZ4 vectors will be skipped")
    else:
        lz4 = lz4.block

    manifest = []
    for name, data in payloads().items():
        with open(os.path.join(args.out, f"{name}.bin"), "wb") as fh:
            fh.write(data)

        # Only the container formats Minecraft actually uses. Anvil chunk
        # payloads are zlib or gzip (selected by the compression byte in the
        # chunk header), level.dat on both editions is gzip, and Bedrock
        # subchunks are headerless LZ4 blocks. Raw deflate appears in no
        # Minecraft format, so it is deliberately not generated or tested.
        with open(os.path.join(args.out, f"{name}.zlib"), "wb") as fh:
            fh.write(zlib.compress(data, 9, 15))
        with open(os.path.join(args.out, f"{name}.gz"), "wb") as fh:
            fh.write(zlib.compress(data, 9, 15 + 16))
        if lz4 is not None:
            with open(os.path.join(args.out, f"{name}.lz4"), "wb") as fh:
                fh.write(lz4.compress(data, store_size=False))

        manifest.append((name, len(data)))
        _log(f"{name}: {len(data)} bytes")

    with open(os.path.join(args.out, "MANIFEST.txt"), "w", encoding="utf-8") as fh:
        fh.write("# name,plain-bytes  (generated by tools/ref_compress.py)\n")
        for name, size in manifest:
            fh.write(f"{name} {size}\n")

    _log(f"wrote {len(manifest)} payloads to {args.out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
